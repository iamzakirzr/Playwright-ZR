export function getCategory(id: string): ToolCategory | undefined {
  return toolCategories.find((category) => category.id === id);
}

export function getTool(
  categoryId: string,
  toolId: string,
): { category: ToolCategory; tool: AcademyToolSafe } | undefined {
  const category = getCategory(categoryId);
  if (!category) {
    return undefined;
  }
  const tool = category.tools.find((item) => item.id === toolId);
  if (!tool) {
    return undefined;
  }
  return { category, tool };
}

type AcademyToolSafe = ToolCategory["tools"][number];

export function isCategoryId(value: string): value is ToolCategoryId {
  return toolCategories.some((category) => category.id === value);
}
